local display
local frames = 0

memory.registerexec(0x020a09c0, function()
   local count = memory.getregister("r1")
   local id = memory.getregister("r2")
   local name = itemList[id] or "-"
   display = string.format("%s: %d", string.upper(name), count)
   frames = 0
end)

gui.register(function()
   if display then
      if frames < 300 then
         gui.text(5, -187, display)
         frames = frames + 1
      else
         display = nil
      end
   end
end)
